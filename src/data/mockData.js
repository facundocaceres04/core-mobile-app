// Helper to generate schedule grid for any sede and date
export function generateScheduleForDay(dateId, sedeId) {
  const totalCapacity = 12;

  const hours = [
    { time: "07:00", coach: "Santi V.", defaultOccupied: 12 },
    { time: "08:00", coach: "Santi V.", defaultOccupied: 12 },
    { time: "09:00", coach: "Matías R.", defaultOccupied: 12 },
    { time: "10:00", coach: "Matías R.", defaultOccupied: 12 },
    { time: "11:00", coach: "Joaquín P.", defaultOccupied: 12 },
    { time: "12:00", coach: "Joaquín P.", defaultOccupied: 11 },
    { time: "15:00", coach: "Lucas B.", defaultOccupied: 6 },
    { time: "16:00", coach: "Lucas B.", defaultOccupied: 8 },
    { time: "17:00", coach: "Agustín S.", defaultOccupied: 10 },
    { time: "18:00", coach: "Agustín S.", defaultOccupied: 11 },
    { time: "19:00", coach: "Matías R.", defaultOccupied: 12 },
    { time: "20:00", coach: "Matías R.", defaultOccupied: 12 },
  ];

  const seed = (dateId + sedeId).split('').reduce((acc, char) => acc + char.charCodeAt(0), 0);

  return hours.map((item, idx) => {
    let occupied = (item.defaultOccupied + (seed + idx) % 5) % (totalCapacity + 1);
    if (idx === 6) occupied = 6;

    const freeSpots = Math.max(0, totalCapacity - occupied);
    const isFull = freeSpots === 0;

    return {
      id: `${sedeId}_${dateId}_${item.time}`,
      time: item.time,
      duration: "50 min • Calistenia & Peso Corporal",
      coach: item.coach,
      totalCapacity,
      occupied,
      freeSpots,
      isFull,
    };
  });
}

